#       Extract validation logic (lines 293–315) and file generation (lines 340–363) into
#       separate functions.
def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")

    parser = argparse.ArgumentParser(
        description="Generate per-tenant docker-compose and .env files.",
    )
    parser.add_argument(
        "input",
        type=Path,
        help="Path to tenants/<tenant>.env input file.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite existing output files if present.",
    )
    args = parser.parse_args(argv)

    try:
        input_vars = parse_env_file(args.input)
    except (FileNotFoundError, ValueError) as exc:
        logger.error(str(exc))
        return 1

    if "PORT_OFFSET" not in input_vars:
        logger.error("Required key missing in input: PORT_OFFSET")
        return 1

    stem = args.input.stem
    if stem == "example":
        logger.error("tenants/example.env is a template — copy it first:\n  cp tenants/example.env tenants/<your-tenant>.env")
        return 1

    file_tenant_id = input_vars.get("TENANT_ID")
    if file_tenant_id is not None and file_tenant_id != stem:
        logger.error(
            f"Tenant ID mismatch: filename stem is '{stem}' but TENANT_ID='{file_tenant_id}'.\nRecommended: drop TENANT_ID from the input file — it's now derived from the filename."
        )
        return 1

    try:
        tenant_id = validate_tenant_id(stem)
        port_offset = validate_port_offset(input_vars["PORT_OFFSET"])
    except ValueError as exc:
        logger.error(str(exc))
        return 1

    repo_root = Path.cwd()
    compose_path = repo_root / f"docker-compose.{tenant_id}.yml"
    env_path = repo_root / f".env.{tenant_id}"

    if not args.force:
        existing = [p for p in (compose_path, env_path) if p.exists()]
        if existing:
            joined = "\n  ".join(str(p) for p in existing)
            logger.error(f"Refusing to overwrite existing files (use --force):\n  {joined}")
            return 1

    minio_access_key = input_vars.get("MINIO_ACCESS_KEY", DEFAULT_MINIO_ACCESS_KEY)
    minio_secret_key = input_vars.get("MINIO_SECRET_KEY", DEFAULT_MINIO_SECRET_KEY)
    minio_bucket_name = input_vars.get("MINIO_BUCKET_NAME", DEFAULT_MINIO_BUCKET_NAME)
    milvus_host = input_vars.get("MILVUS_HOST", DEFAULT_HOST) or DEFAULT_HOST
    minio_host = input_vars.get("MINIO_HOST", DEFAULT_HOST) or DEFAULT_HOST
    redis_host = input_vars.get("REDIS_HOST", DEFAULT_HOST) or DEFAULT_HOST
    minio_public_endpoint = input_vars.get("MINIO_PUBLIC_ENDPOINT") or None
    minio_public_secure = input_vars.get("MINIO_PUBLIC_SECURE") or None

    compose_text = render_compose(
        tenant_id,
        port_offset,
        minio_access_key,
        minio_secret_key,
    )
    env_text = render_app_env(
        tenant_id,
        port_offset,
        input_vars,
        minio_access_key,
        minio_secret_key,
        minio_bucket_name,
        milvus_host,
        minio_host,
        redis_host,
        minio_public_endpoint,
        minio_public_secure,
    )

    try:
        compose_path.write_text(compose_text, encoding="utf-8")
        env_path.write_text(env_text, encoding="utf-8")
        create_volume_dirs(repo_root, tenant_id)
    except OSError as exc:
        logger.error(f"Failed to write tenant stack files: {exc}")
        for partial in (compose_path, env_path):
            if partial.exists():
                try:
                    partial.unlink()
                except OSError:
                    logger.warning(f"Could not clean up partial file: {partial}")
        return 1

    logger.info(f"Wrote {compose_path.relative_to(repo_root)}")
    logger.info(f"Wrote {env_path.relative_to(repo_root)}")
    logger.info(f"Created ./volumes/{tenant_id}/{{{','.join(SERVICE_VOLUME_NAMES)}}}")
    print_next_steps(tenant_id)
    return 0


if __name__ == "__main__":
    sys.exit(main())
