"""Generate per-tenant docker-compose and app .env from a tenant input file.

Usage:
    poetry run gen-tenant tenants/<tenant>.env [--force]

Outputs (written at repo root):
    docker-compose.<tenant>.yml   parameterized infra stack
    .env.<tenant>                 consumed by FastAPI via pydantic-settings
    ./volumes/<tenant>/{etcd,minio,milvus,redis}   bind-mount roots

After generation:
    docker compose -f docker-compose.<tenant>.yml -p <tenant> up -d
    ln -sf .env.<tenant> .env
    poetry run start
"""

from __future__ import annotations

import argparse
import logging
import re
import sys
from pathlib import Path

logger = logging.getLogger(__name__)

MINIO_API_PORT_BASE = 9002
MINIO_CONSOLE_PORT_BASE = 9003
MILVUS_GRPC_PORT_BASE = 19531
MILVUS_HEALTH_PORT_BASE = 9092
REDIS_PORT_BASE = 6379
APP_PORT_BASE = 8001

PORT_OFFSET_STEP = 100
PORT_OFFSET_MAX = 9000

TENANT_ID_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]*$")

SERVICE_VOLUME_NAMES: tuple[str, ...] = ("etcd", "minio", "milvus", "redis")

DEFAULT_MINIO_ACCESS_KEY = "minioadmin"
DEFAULT_MINIO_SECRET_KEY = "minioadmin"  # noqa: S105
DEFAULT_MINIO_BUCKET_NAME = "rag-storage"
DEFAULT_APP_ENV = "dev"
DEFAULT_MINIO_SECURE = "false"
DEFAULT_MINIO_PUBLIC_SECURE = "true"
DEFAULT_HOST = "localhost"

CARRY_THROUGH_PREFIXES: tuple[str, ...] = ("LLM__", "DOC_PARSER__", "KEYCLOAK__")
MILVUS_CARRY_THROUGH_KEYS: tuple[str, ...] = (
    "MILVUS__CORPUS_COLLECTION_NAME",
    "MILVUS__INPUT_COLLECTION_NAME",
    "MILVUS__VECTOR_DIM",
    "MILVUS__METRIC_TYPE",
)


def parse_env_file(path: Path) -> dict[str, str]:
    if not path.exists():
        raise FileNotFoundError(f"Tenant input file not found: {path}")

    out: dict[str, str] = {}
    with path.open("r", encoding="utf-8") as fh:
        for line_num, raw_line in enumerate(fh, start=1):
            stripped = raw_line.strip()
            if not stripped or stripped.startswith("#"):
                continue

            if "=" not in stripped:
                raise ValueError(f"{path}:{line_num}: expected KEY=VALUE, got: {raw_line.rstrip()}")

            key, _, value = stripped.partition("=")
            key = key.strip()
            value = value.strip()

            if len(value) >= 2 and value[0] in ("'", '"') and value[-1] == value[0]:
                value = value[1:-1]

            out[key] = value

    return out


def validate_tenant_id(value: str) -> str:
    if not TENANT_ID_PATTERN.match(value):
        raise ValueError(f"Invalid TENANT_ID '{value}': must match {TENANT_ID_PATTERN.pattern}")
    return value


def validate_port_offset(value: str) -> int:
    try:
        offset = int(value)
    except ValueError as exc:
        raise ValueError(f"PORT_OFFSET must be an integer, got '{value}'") from exc

    if offset < 0 or offset > PORT_OFFSET_MAX:
        raise ValueError(f"PORT_OFFSET out of range [0..{PORT_OFFSET_MAX}]: {offset}")

    if offset % PORT_OFFSET_STEP != 0:
        raise ValueError(f"PORT_OFFSET must be a multiple of {PORT_OFFSET_STEP}: {offset}")

    return offset


