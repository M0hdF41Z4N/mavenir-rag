def render_compose(
    tenant_id: str,
    port_offset: int,
    minio_access_key: str,
    minio_secret_key: str,
) -> str:
    minio_api_host = MINIO_API_PORT_BASE + port_offset
    minio_console_host = MINIO_CONSOLE_PORT_BASE + port_offset
    milvus_grpc_host = MILVUS_GRPC_PORT_BASE + port_offset
    milvus_health_host = MILVUS_HEALTH_PORT_BASE + port_offset
    redis_host = REDIS_PORT_BASE + port_offset

    return f"""# Generated by api/scripts/gen_tenant_stack.py — do not hand-edit.
# Tenant: {tenant_id}    Port offset: {port_offset}
version: "3.5"

services:
  etcd:
    container_name: {tenant_id}-milvus-etcd
    image: quay.io/coreos/etcd:v3.5.25
    environment:
      - ETCD_AUTO_COMPACTION_MODE=revision
      - ETCD_AUTO_COMPACTION_RETENTION=1000
      - ETCD_QUOTA_BACKEND_BYTES=4294967296
      - ETCD_SNAPSHOT_COUNT=50000
    volumes:
      - ./volumes/{tenant_id}/etcd:/etcd
    command: etcd -advertise-client-urls=http://etcd:2379 -listen-client-urls http://0.0.0.0:2379 --data-dir /etcd
    healthcheck:
      test: ["CMD", "etcdctl", "endpoint", "health"]
      interval: 30s
      timeout: 20s
      retries: 3

  minio:
    container_name: {tenant_id}-milvus-minio
    image: minio/minio:RELEASE.2024-12-18T13-15-44Z
    environment:
      MINIO_ACCESS_KEY: {minio_access_key}
      MINIO_SECRET_KEY: {minio_secret_key}
      # Open CORS for browser-side presigned downloads. Presigned URLs already
      # carry the access capability; origin restriction adds no real security.
      MINIO_API_CORS_ALLOW_ORIGIN: "*"
    ports:
      - "{minio_console_host}:9001"
      - "{minio_api_host}:9000"
    volumes:
      - ./volumes/{tenant_id}/minio:/minio_data
    command: minio server /minio_data --console-address ":9001"
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:9000/minio/health/live"]
      interval: 30s
      timeout: 20s
      retries: 3

  standalone:
    container_name: {tenant_id}-milvus-standalone
    image: milvusdb/milvus:v2.6.11
    command: ["milvus", "run", "standalone"]
    security_opt:
      - seccomp:unconfined
    environment:
      ETCD_ENDPOINTS: etcd:2379
      MINIO_ADDRESS: minio:9000
      MQ_TYPE: woodpecker
    volumes:
      - ./volumes/{tenant_id}/milvus:/var/lib/milvus
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:9091/healthz"]
      interval: 30s
      start_period: 90s
      timeout: 20s
      retries: 3
    ports:
      - "{milvus_grpc_host}:19530"
      - "{milvus_health_host}:9091"
    depends_on:
      - "etcd"
      - "minio"

  redis:
    container_name: {tenant_id}-redis
    image: redis/redis-stack-server:latest
    ports:
      - "{redis_host}:6379"
    volumes:
      - ./volumes/{tenant_id}/redis:/data
    restart: always

networks:
  default:
    name: {tenant_id}-milvus
"""


# TODO: render_app_env() violates two limits (Coding conventions §5): 57+ lines (exceeds 50)
#       and 9 parameters (exceeds 5). Use a dataclass to bundle the ports/credentials and
#       reduce parameters.
def render_app_env(
    tenant_id: str,
    port_offset: int,
    input_vars: dict[str, str],
    minio_access_key: str,
    minio_secret_key: str,
    minio_bucket_name: str,
    milvus_host: str,
    minio_host: str,
    redis_host: str,
    minio_public_endpoint: str | None,
    minio_public_secure: str | None,
) -> str:
    minio_api_host_port = MINIO_API_PORT_BASE + port_offset
    milvus_grpc_host_port = MILVUS_GRPC_PORT_BASE + port_offset
    redis_host_port = REDIS_PORT_BASE + port_offset
    app_port = APP_PORT_BASE + port_offset

    lines: list[str] = [
        "# Generated by api/scripts/gen_tenant_stack.py — do not hand-edit.",
        f"# Tenant: {tenant_id}    Port offset: {port_offset}",
        "",
        f"APP_ENV={input_vars.get('APP_ENV', DEFAULT_APP_ENV)}",
        f"APP_PORT={app_port}",
        "",
        "# Milvus (host-side connection)",
        f"MILVUS__HOST={milvus_host}",
        f"MILVUS__PORT={milvus_grpc_host_port}",
    ]

    for key in MILVUS_CARRY_THROUGH_KEYS:
        if key in input_vars:
            lines.append(f"{key}={input_vars[key]}")

    lines.extend(
        [
            "",
            "# MinIO (host-side connection)",
            f"MINIO__ENDPOINT={minio_host}:{minio_api_host_port}",
            f"MINIO__ACCESS_KEY={minio_access_key}",
            f"MINIO__SECRET_KEY={minio_secret_key}",
            f"MINIO__BUCKET_NAME={minio_bucket_name}",
            f"MINIO__SECURE={input_vars.get('MINIO__SECURE', DEFAULT_MINIO_SECURE)}",
        ]
    )

    if minio_public_endpoint:
        lines.append(f"MINIO__PUBLIC_ENDPOINT={minio_public_endpoint}")
        lines.append(f"MINIO__PUBLIC_SECURE={minio_public_secure or DEFAULT_MINIO_PUBLIC_SECURE}")

    lines.extend(
        [
            "",
            "# Redis (host-side connection)",
            f"REDIS__REDIS_URL=redis://{redis_host}:{redis_host_port}",
            "",
        ]
    )

    section_labels = {
        "LLM__": "# LLM",
        "DOC_PARSER__": "# Document parser",
        "KEYCLOAK__": "# Keycloak",
    }
    for prefix in CARRY_THROUGH_PREFIXES:
        carried = {k: v for k, v in input_vars.items() if k.startswith(prefix)}
        if not carried:
            continue
        lines.append(section_labels[prefix])
        for key in sorted(carried):
            lines.append(f"{key}={carried[key]}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def create_volume_dirs(repo_root: Path, tenant_id: str) -> None:
    base = repo_root / "volumes" / tenant_id
    for service_name in SERVICE_VOLUME_NAMES:
        (base / service_name).mkdir(parents=True, exist_ok=True)


def print_next_steps(tenant_id: str) -> None:
    project_arg = f"-p {tenant_id}"
    file_arg = f"-f docker-compose.{tenant_id}.yml"
    print()
    print(f"Generated stack files for tenant '{tenant_id}'. Next steps:")
    print()
    print(f"  docker compose {file_arg} {project_arg} up -d")
    print(f"  ln -sf .env.{tenant_id} .env")
    print("  poetry run start")
    print()
    print("To tear down:")
    print(f"  docker compose {file_arg} {project_arg} down")
    print()


